import '../../../core/configs/project_config.dart';

/// Generates `.github/workflows/flutter_ci.yml` for GitHub Actions.
class GitHubActionsTemplate {
  static String content(ProjectConfig config) {
    const flavor = ProjectConfig.defaultCiFlavor;
    final mainEntry = 'lib/main_$flavor.dart';
    final codegenStep = config.needsCodegen
        ? '''
      - name: Build_runner
        run: dart run build_runner build --delete-conflicting-outputs
'''
        : '';

    final buffer = StringBuffer();
    buffer.writeln('# Generated by XProject Generator');
    buffer.writeln('name: Flutter CI');
    buffer.writeln();
    buffer.writeln('on:');
    buffer.writeln('  push:');
    buffer.writeln('    branches: [main, master]');
    buffer.writeln('  pull_request:');
    buffer.writeln('  workflow_dispatch:');
    buffer.writeln();
    buffer.writeln('concurrency:');
    buffer.writeln('  group: \${{ github.workflow }}-\${{ github.ref }}');
    buffer.writeln('  cancel-in-progress: true');
    buffer.writeln();
    buffer.writeln('jobs:');
    buffer.writeln('  analyze_and_test:');
    buffer.writeln('    runs-on: ubuntu-latest');
    buffer.writeln('    steps:');
    buffer.writeln('      - uses: actions/checkout@v4');
    buffer.writeln('      - uses: subosito/flutter-action@v2');
    buffer.writeln('        with:');
    buffer.writeln('          channel: stable');
    buffer.writeln('          cache: true');
    buffer.writeln('      - name: Pub get');
    buffer.writeln('        run: flutter pub get');
    buffer.writeln(codegenStep);
    buffer.writeln('      - name: Analyze');
    buffer.writeln('        run: flutter analyze');
    buffer.writeln('      - name: Test');
    buffer.writeln('        run: flutter test');
    buffer.writeln();

    if (!config.hasCiDeploy) {
      return buffer.toString().trimRight();
    }

    if (config.targetsAndroid) {
      buffer.writeln('  build_android_$flavor:');
      buffer.writeln('    needs: analyze_and_test');
      buffer.writeln('    runs-on: ubuntu-latest');
      buffer.writeln('    if: github.event_name == \'workflow_dispatch\'');
      buffer.writeln('    steps:');
      buffer.writeln('      - uses: actions/checkout@v4');
      buffer.writeln('      - uses: subosito/flutter-action@v2');
      buffer.writeln('        with:');
      buffer.writeln('          channel: stable');
      buffer.writeln('          cache: true');
      buffer.writeln('      - run: flutter pub get');
      if (config.needsCodegen) {
        buffer.writeln(
          '      - run: dart run build_runner build --delete-conflicting-outputs',
        );
      }
      buffer.writeln(
        '      - run: flutter build appbundle --release --flavor $flavor -t $mainEntry',
      );
      buffer.writeln('      - uses: actions/upload-artifact@v4');
      buffer.writeln('        with:');
      buffer.writeln('          name: android-$flavor-aab');
      buffer.writeln('          path: build/app/outputs/');
      buffer.writeln();
    }

    if (config.targetsIos) {
      buffer.writeln('  build_ios_$flavor:');
      buffer.writeln('    needs: analyze_and_test');
      buffer.writeln('    runs-on: macos-latest');
      buffer.writeln('    if: github.event_name == \'workflow_dispatch\'');
      buffer.writeln('    steps:');
      buffer.writeln('      - uses: actions/checkout@v4');
      buffer.writeln('      - uses: subosito/flutter-action@v2');
      buffer.writeln('        with:');
      buffer.writeln('          channel: stable');
      buffer.writeln('          cache: true');
      buffer.writeln('      - run: flutter pub get');
      buffer.writeln('      - run: cd ios && pod install && cd ..');
      if (config.needsCodegen) {
        buffer.writeln(
          '      - run: dart run build_runner build --delete-conflicting-outputs',
        );
      }
      buffer.writeln(
        '      - run: flutter build ipa --release --flavor $flavor -t $mainEntry',
      );
      buffer.writeln('      - uses: actions/upload-artifact@v4');
      buffer.writeln('        with:');
      buffer.writeln('          name: ios-$flavor-ipa');
      buffer.writeln('          path: build/ios/ipa/');
      buffer.writeln();
    }

    final deploy = config.resolvedDeployTargets;
    if (deploy.contains(DeployTarget.playInternal) && config.targetsAndroid) {
      buffer.writeln('  deploy_play_internal:');
      buffer.writeln('    needs: build_android_$flavor');
      buffer.writeln('    runs-on: ubuntu-latest');
      buffer.writeln('    if: github.event_name == \'workflow_dispatch\'');
      buffer.writeln('    steps:');
      buffer.writeln('      - uses: actions/checkout@v4');
      buffer.writeln('      - uses: ruby/setup-ruby@v1');
      buffer.writeln('        with:');
      buffer.writeln('          ruby-version: \'3.2\'');
      buffer.writeln('          bundler-cache: true');
      buffer.writeln('      - run: bundle exec fastlane deploy_play_internal');
      buffer.writeln('        working-directory: fastlane');
      buffer.writeln('        env:');
      buffer.writeln('          PLAY_JSON_KEY_FILE: \${{ secrets.PLAY_JSON_KEY_FILE }}');
      buffer.writeln();
    }

    if (deploy.contains(DeployTarget.testFlight) && config.targetsIos) {
      buffer.writeln('  deploy_testflight:');
      buffer.writeln('    needs: build_ios_$flavor');
      buffer.writeln('    runs-on: macos-latest');
      buffer.writeln('    if: github.event_name == \'workflow_dispatch\'');
      buffer.writeln('    steps:');
      buffer.writeln('      - uses: actions/checkout@v4');
      buffer.writeln('      - uses: ruby/setup-ruby@v1');
      buffer.writeln('      - run: bundle exec fastlane deploy_testflight');
      buffer.writeln('        working-directory: fastlane');
      buffer.writeln();
    }

    if (deploy.contains(DeployTarget.firebaseAppDistribution) &&
        (config.targetsAndroid || config.targetsIos)) {
      final needs = config.targetsAndroid
          ? 'build_android_$flavor'
          : 'build_ios_$flavor';
      final runsOn = config.targetsIos && !config.targetsAndroid
          ? 'macos-latest'
          : 'ubuntu-latest';
      buffer.writeln('  deploy_firebase_app_distribution:');
      buffer.writeln('    needs: $needs');
      buffer.writeln('    runs-on: $runsOn');
      buffer.writeln('    if: github.event_name == \'workflow_dispatch\'');
      buffer.writeln('    steps:');
      buffer.writeln('      - uses: actions/checkout@v4');
      buffer.writeln('      - uses: ruby/setup-ruby@v1');
      buffer.writeln('        with:');
      buffer.writeln('          ruby-version: \'3.2\'');
      buffer.writeln('          bundler-cache: true');
      buffer.writeln('      - run: bundle exec fastlane deploy_firebase');
      buffer.writeln('        working-directory: fastlane');
      buffer.writeln('        env:');
      buffer.writeln('          FIREBASE_TOKEN: \${{ secrets.FIREBASE_TOKEN }}');
      buffer.writeln(
        '          FIREBASE_APP_ID_ANDROID: \${{ secrets.FIREBASE_APP_ID_ANDROID }}',
      );
      buffer.writeln(
        '          FIREBASE_APP_ID_IOS: \${{ secrets.FIREBASE_APP_ID_IOS }}',
      );
      buffer.writeln();
    }

    return buffer.toString().trimRight();
  }
}
