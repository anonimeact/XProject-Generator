import '../../../core/configs/project_config.dart';

/// Generates `.gitlab-ci.yml` for scaffolded Flutter projects.
class GitlabCiTemplate {
  static String content(ProjectConfig config) {
    const flavor = ProjectConfig.defaultCiFlavor;
    final mainEntry = 'lib/main_$flavor.dart';
    final buffer = StringBuffer();
    buffer.writeln('# Generated by XProject Generator — adjust rules/variables as needed.');
    buffer.writeln('stages:');
    buffer.writeln('  - quality');
    buffer.writeln('  - test');
    if (config.hasCiDeploy) {
      buffer.writeln('  - build');
      if (config.resolvedDeployTargets.any(
        (t) =>
            t == DeployTarget.playInternal ||
            t == DeployTarget.testFlight ||
            t == DeployTarget.firebaseAppDistribution,
      )) {
        buffer.writeln('  - deploy');
      }
    }
    buffer.writeln();
    buffer.writeln('variables:');
    buffer.writeln('  PUB_CACHE: "\$CI_PROJECT_DIR/.pub-cache"');
    buffer.writeln();
    buffer.writeln('.flutter_before:');
    if (config.gitLabSelfHostedShell) {
      buffer.writeln(
        '  # Self-hosted shell — lihat ci/GITLAB_RUNNER_SETUP.md; tags di setiap job.',
      );
    } else if (config.gitlabRunnerMode == GitLabRunnerMode.dockerfile) {
      buffer.writeln('  image:');
      buffer.writeln('    name: \$CI_REGISTRY_IMAGE/ci-flutter:latest');
      buffer.writeln('    pull_policy: if-not-present');
    } else {
      buffer.writeln('  image: ghcr.io/cirruslabs/flutter:stable');
    }
    buffer.writeln('  before_script:');
    buffer.writeln('    - flutter --version');
    buffer.writeln('    - flutter pub get');
    if (config.needsCodegen) {
      buffer.writeln(
        '    - dart run build_runner build --delete-conflicting-outputs',
      );
    }
    buffer.writeln('  cache:');
    buffer.writeln('    key: "\${CI_COMMIT_REF_SLUG}-pub"');
    buffer.writeln('    paths:');
    buffer.writeln('      - .pub-cache/');
    buffer.writeln('      - .dart_tool/');
    buffer.writeln();

    buffer.writeln('analyze:');
    buffer.writeln('  stage: quality');
    buffer.writeln('  extends: .flutter_before');
    _writeDefaultRunnerTags(buffer, config);
    buffer.writeln('  script:');
    buffer.writeln('    - flutter analyze');
    buffer.writeln('  rules:');
    buffer.writeln('    - if: \$CI_PIPELINE_SOURCE == "merge_request_event"');
    buffer.writeln('    - if: \$CI_COMMIT_BRANCH == \$CI_DEFAULT_BRANCH');
    buffer.writeln();

    buffer.writeln('unit_test:');
    buffer.writeln('  stage: test');
    buffer.writeln('  extends: .flutter_before');
    _writeDefaultRunnerTags(buffer, config);
    buffer.writeln('  script:');
    buffer.writeln('    - flutter test');
    buffer.writeln('  rules:');
    buffer.writeln('    - if: \$CI_PIPELINE_SOURCE == "merge_request_event"');
    buffer.writeln('    - if: \$CI_COMMIT_BRANCH == \$CI_DEFAULT_BRANCH');
    buffer.writeln();

    if (!config.hasCiDeploy) {
      return buffer.toString().trimRight();
    }

    if (config.targetsAndroid) {
      buffer.writeln('build_android_$flavor:');
      buffer.writeln('  stage: build');
      buffer.writeln('  extends: .flutter_before');
      _writeDefaultRunnerTags(buffer, config);
      buffer.writeln('  script:');
      buffer.writeln(
        '    - flutter build appbundle --release --flavor $flavor -t $mainEntry',
      );
      buffer.writeln('  artifacts:');
      buffer.writeln('    paths:');
      buffer.writeln('      - build/app/outputs/');
      buffer.writeln('    expire_in: 1 week');
      buffer.writeln('  rules:');
      buffer.writeln('    - if: \$CI_COMMIT_BRANCH == \$CI_DEFAULT_BRANCH');
      buffer.writeln('      when: manual');
      buffer.writeln();
    }

    if (config.targetsIos) {
      buffer.writeln('build_ios_$flavor:');
      buffer.writeln('  stage: build');
      buffer.writeln('  extends: .flutter_before');
      _writeIosRunnerTags(buffer, config);
      buffer.writeln('  script:');
      buffer.writeln(
        '    - flutter build ipa --release --flavor $flavor -t $mainEntry',
      );
      buffer.writeln('  artifacts:');
      buffer.writeln('    paths:');
      buffer.writeln('      - build/ios/ipa/');
      buffer.writeln('    expire_in: 1 week');
      buffer.writeln('  rules:');
      buffer.writeln('    - if: \$CI_COMMIT_BRANCH == \$CI_DEFAULT_BRANCH');
      buffer.writeln('      when: manual');
      buffer.writeln();
    }

    final deploy = config.resolvedDeployTargets;
    if (deploy.contains(DeployTarget.playInternal) && config.targetsAndroid) {
      buffer.writeln('deploy_play_internal:');
      buffer.writeln('  stage: deploy');
      buffer.writeln('  extends: .flutter_before');
      _writeDefaultRunnerTags(buffer, config);
      buffer.writeln('  needs: ["build_android_$flavor"]');
      buffer.writeln('  script:');
      buffer.writeln('    - cd fastlane && bundle exec fastlane deploy_play_internal');
      buffer.writeln('  rules:');
      buffer.writeln('    - if: \$CI_COMMIT_BRANCH == \$CI_DEFAULT_BRANCH');
      buffer.writeln('      when: manual');
      buffer.writeln();
    }

    if (deploy.contains(DeployTarget.testFlight) && config.targetsIos) {
      buffer.writeln('deploy_testflight:');
      buffer.writeln('  stage: deploy');
      buffer.writeln('  extends: .flutter_before');
      _writeIosRunnerTags(buffer, config);
      buffer.writeln('  needs: ["build_ios_$flavor"]');
      buffer.writeln('  script:');
      buffer.writeln('    - cd fastlane && bundle exec fastlane deploy_testflight');
      buffer.writeln('  rules:');
      buffer.writeln('    - if: \$CI_COMMIT_BRANCH == \$CI_DEFAULT_BRANCH');
      buffer.writeln('      when: manual');
      buffer.writeln();
    }

    if (deploy.contains(DeployTarget.firebaseAppDistribution)) {
      buffer.writeln('deploy_firebase_app_distribution:');
      buffer.writeln('  stage: deploy');
      buffer.writeln('  extends: .flutter_before');
      _writeDefaultRunnerTags(buffer, config);
      if (config.targetsAndroid) {
        buffer.writeln('  needs: ["build_android_$flavor"]');
      }
      buffer.writeln('  script:');
      buffer.writeln(
        '    - cd fastlane && bundle exec fastlane deploy_firebase',
      );
      buffer.writeln('  rules:');
      buffer.writeln('    - if: \$CI_COMMIT_BRANCH == \$CI_DEFAULT_BRANCH');
      buffer.writeln('      when: manual');
      buffer.writeln();
    }

    return buffer.toString().trimRight();
  }

  static void _writeDefaultRunnerTags(
    StringBuffer buffer,
    ProjectConfig config,
  ) {
    if (!config.gitLabSelfHostedShell) return;
    buffer.writeln('  tags:');
    buffer.writeln('    - self-hosted');
    buffer.writeln('    - flutter');
  }

  static void _writeIosRunnerTags(StringBuffer buffer, ProjectConfig config) {
    buffer.writeln('  tags:');
    if (config.gitLabSelfHostedShell) {
      buffer.writeln('    - self-hosted');
      buffer.writeln('    - flutter');
      buffer.writeln('    - macos');
    } else {
      buffer.writeln('    - macos');
    }
  }
}
